create table if not exists public.play_achievements (
  id bigint generated by default as identity primary key,
  score integer not null default 0 check (score >= 0),
  hits integer not null default 0 check (hits >= 0),
  wrong integer not null default 0 check (wrong >= 0),
  missed integer not null default 0 check (missed >= 0),
  timed_out boolean not null default false,
  achievement_id text not null check (
    achievement_id in (
      'perfect_hunter',
      'sniper',
      'master_of_cynicism',
      'dawn_of_cynicism',
      'half_and_half',
      'keep_trying',
      'trigger_happy',
      'cold_observer',
      'hot_blooded'
    )
  ),
  achievement_title text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_play_achievements_created_at
  on public.play_achievements (created_at desc);

alter table public.play_achievements enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'play_achievements'
      and policyname = 'Allow public insert access on play_achievements'
  ) then
    create policy "Allow public insert access on play_achievements"
      on public.play_achievements
      for insert
      to anon, authenticated
      with check (true);
  end if;
end
$$;
