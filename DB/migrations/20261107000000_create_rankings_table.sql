create table if not exists public.rankings (
  id bigint generated by default as identity primary key,
  result_id uuid not null unique,
  name text not null check (
    char_length(trim(name)) between 1 and 20
    and name !~ '[[:cntrl:]]'
  ),
  score integer not null check (score >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_rankings_score_created_at
  on public.rankings (score desc, created_at asc);

alter table public.rankings enable row level security;

do $$
begin
  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'rankings'
      and policyname = 'Allow public read access on rankings'
  ) then
    create policy "Allow public read access on rankings"
      on public.rankings
      for select
      to anon, authenticated
      using (true);
  end if;

  if not exists (
    select 1
    from pg_policies
    where schemaname = 'public'
      and tablename = 'rankings'
      and policyname = 'Allow public insert access on rankings'
  ) then
    create policy "Allow public insert access on rankings"
      on public.rankings
      for insert
      to anon, authenticated
      with check (true);
  end if;
end
$$;
