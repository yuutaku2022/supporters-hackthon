-- 1プレイごとの得点・回答挙動・獲得した称号（実績）を保存するテーブル
-- achievement_id:
--   'perfect_hunter'   : 俺じゃなきゃ見逃しちゃうね（制限時間内のノーミス）
--   'dawn_of_cynicism' : 冷笑の夜明け（正答率が半分以上）
--   'keep_trying'      : 君，まだまだっすねw（正答率が半分未満）
--   'cold_observer'    : 冷笑の観測者（制限時間内に回答を1回もしなかった）
--   'hot_blooded'      : 熱血の申し子（全ての回答で誤答を選んだ）

create table if not exists public.play_achievements (
  id bigint generated by default as identity primary key,
  score integer not null default 0,
  hits integer not null default 0 check (hits >= 0),
  wrong integer not null default 0 check (wrong >= 0),
  missed integer not null default 0 check (missed >= 0),
  timed_out boolean not null default false,
  achievement_id text not null check (
    achievement_id in (
      'perfect_hunter',
      'dawn_of_cynicism',
      'keep_trying',
      'cold_observer',
      'hot_blooded'
    )
  ),
  achievement_title text not null,
  created_at timestamptz not null default now()
);

comment on table public.play_achievements is '1プレイごとの得点・プレイ挙動（正解数/誤答数/見逃し数/時間切れ）と獲得した称号を管理するテーブル';
comment on column public.play_achievements.id is '一意のID';
comment on column public.play_achievements.score is '1ゲームの合計スコア';
comment on column public.play_achievements.hits is '正解（冷笑を見抜いた）数';
comment on column public.play_achievements.wrong is '誤答（普通のポストを選んだ）数';
comment on column public.play_achievements.missed is '見逃した冷笑ポスト数';
comment on column public.play_achievements.timed_out is '制限時間切れまたは未クリアが含まれるか';
comment on column public.play_achievements.achievement_id is '獲得した称号の識別子';
comment on column public.play_achievements.achievement_title is '獲得した称号名';
comment on column public.play_achievements.created_at is 'レコード作成日時';

-- 検索・集計用のインデックス
create index if not exists idx_play_achievements_achievement_id on public.play_achievements (achievement_id);
create index if not exists idx_play_achievements_created_at on public.play_achievements (created_at desc);

-- Row Level Security (RLS) の有効化
alter table public.play_achievements enable row level security;

-- 公開読み取りポリシー（anon / authenticated から SELECT 可能）
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'play_achievements'
      and policyname = 'Allow public read access on play_achievements'
  ) then
    create policy "Allow public read access on play_achievements"
      on public.play_achievements
      for select
      to anon, authenticated
      using (true);
  end if;
end
$$;

-- 公開書き込みポリシー（ゲーム終了時に anon / authenticated から INSERT 可能）
do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'play_achievements'
      and policyname = 'Allow public insert access on play_achievements'
  ) then
    create policy "Allow public insert access on play_achievements"
      on public.play_achievements
      for insert
      to anon, authenticated
      with check (true);
  end if;
end
$$;
